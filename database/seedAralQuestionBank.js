async function seedQuestionBank() {
  await connectDB();
  console.log('🌱 Connecting and indexing ARAL Reading Question Bank...');

  // Remove existing reading questions so we have clean authentic data
  const delResult = await Question.deleteMany({ subject: 'Reading' });
  console.log(`🧹 Removed ${delResult.deletedCount} prior Reading questions.`);

  const insertResult = await Question.insertMany(aralReadingQuestions);
  console.log(`✅ Successfully seeded ${insertResult.length} authentic ARAL Reading questions!`);

  // Print summary by topic
  const summary = await Question.aggregate([
    { $match: { subject: 'Reading' } },
    { $group: { _id: '$topic', count: { $sum: 1 } } },
    { $sort: { _id: 1 } },
  ]);

  console.log('\n📊 Questions seeded per topic:');
  for (const s of summary) {
    console.log(`  • ${s._id}: ${s.count} items`);
  }

  process.exit(0);
}

seedQuestionBank().catch((err) => {
  console.error('Error seeding ARAL question bank:', err);
  process.exit(1);
});
